import { INestApplication } from '@nestjs/common';
import * as request from 'supertest';
import { UserStepsController } from '../user-steps.controller';
import { UserStepsService } from '../user-steps.service';
import { UpdateUserStepDto } from '../user-steps.dto';
import { ActivityDetectorInterceptor } from '@/common/interceptors/daily-activity.interceptor';
import { PrismaService } from '@/common/config/prisma/prisma.service';
import { PolicyService } from '@/common/authz/policy.service';
import { DailylogsRepo } from '@/v1/gamify/daily-logs/daily-logs.repo';
import { StreaksRepo } from '@/v1/gamify/streaks/streaks.repo';
import { ADMIN_A, STUDENT_A, STUDENT_B, TEACHER_A, asUser, createHttpApp } from '@/test-utils/http-harness';

const interceptorsOf = (handler: string): unknown[] =>
  Reflect.getMetadata('__interceptors__', (UserStepsController.prototype as any)[handler]) ?? [];

describe('UserStepsController', () => {
  let app: INestApplication;
  let service: { create: jest.Mock; update: jest.Mock; complete: jest.Mock; findOne: jest.Mock; findAll: jest.Mock };

  beforeEach(async () => {
    service = {
      create: jest.fn().mockResolvedValue({ message: 'created', data: [] }),
      update: jest.fn().mockResolvedValue({ message: 'updated', data: null }),
      complete: jest.fn().mockResolvedValue({ message: 'done', data: { id: 'us-1' } }),
      findOne: jest.fn().mockResolvedValue({ message: 'ok', data: { id: 'us-1' } }),
      findAll: jest.fn().mockResolvedValue({ message: 'ok', data: { data: [] } }),
    };
    const prisma = {
      userStep: { findUnique: jest.fn(async ({ where }) => (where.id === 'us-1' ? { userId: STUDENT_A.id } : null)) },
    };
    app = await createHttpApp({
      controllers: [UserStepsController],
      withOwnershipGuard: true,
      providers: [
        { provide: UserStepsService, useValue: service },
        { provide: PrismaService, useValue: prisma },
        PolicyService,
        { provide: DailylogsRepo, useValue: { findToday: jest.fn().mockResolvedValue({ id: 'log-1' }), create: jest.fn() } },
        { provide: StreaksRepo, useValue: { incrementOrReset: jest.fn() } },
      ],
    });
  });

  afterEach(async () => {
    await app.close();
  });

  describe('POST /user-steps', () => {
    const bodyFor = (userId: string) => ({ userId, title: 'Langkah buatan sendiri', order: 1 });
    const body = bodyFor(STUDENT_A.id);

    it.each([
      ['a student', STUDENT_A],
      ['a teacher', TEACHER_A],
    ])('is refused for %s creating a step for themselves, because user steps are generated by the system', async (_label, user) => {
      await request(app.getHttpServer()).post('/user-steps').set(asUser(user)).send(bodyFor(user.id)).expect(403);

      expect(service.create).not.toHaveBeenCalled();
    });

    it('is refused without a session', async () => {
      await request(app.getHttpServer()).post('/user-steps').send(body).expect(401);
    });

    it('stays available to an administrator', async () => {
      await request(app.getHttpServer()).post('/user-steps').set(asUser(ADMIN_A)).send(body).expect(201);

      expect(service.create).toHaveBeenCalledTimes(1);
    });
  });

  describe('PATCH /user-steps/:id', () => {
    it('lets the owner change the step', async () => {
      await request(app.getHttpServer()).patch('/user-steps/us-1').set(asUser(STUDENT_A)).send({ title: 'Judul baru' }).expect(200);

      expect(service.update).toHaveBeenCalledWith('us-1', { title: 'Judul baru' });
    });

    it('is refused for another user', async () => {
      await request(app.getHttpServer()).patch('/user-steps/us-1').set(asUser(STUDENT_B)).send({ title: 'x' }).expect(403);

      expect(service.update).not.toHaveBeenCalled();
    });
  });

  describe('POST /user-steps/complete/:id', () => {
    it('stays available to the owner and is refused to another user', async () => {
      await request(app.getHttpServer()).post('/user-steps/complete/us-1').set(asUser(STUDENT_A)).expect(201);
      await request(app.getHttpServer()).post('/user-steps/complete/us-1').set(asUser(STUDENT_B)).expect(403);

      expect(service.complete).toHaveBeenCalledTimes(1);
    });
  });

  describe('activity credit', () => {
    it('is given for a completion only, not for creating or editing a step', () => {
      expect(interceptorsOf('complete')).toContain(ActivityDetectorInterceptor);
      expect(interceptorsOf('create')).not.toContain(ActivityDetectorInterceptor);
      expect(interceptorsOf('update')).not.toContain(ActivityDetectorInterceptor);
    });
  });
});

describe('UpdateUserStepDto', () => {
  it('lets a client change the title and nothing the server owns', () => {
    const parsed = UpdateUserStepDto.parse({
      title: 'Judul baru',
      userId: 'another-user',
      stepTemplateId: '11111111-1111-4111-8111-111111111111',
      order: 99,
      quizId: '22222222-2222-4222-8222-222222222222',
      isDone: true,
      isUnlocked: true,
    });

    expect(parsed).toEqual({ title: 'Judul baru' });
  });
});
